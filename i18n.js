function english(value) {
  const s = value.trim();
  if (Object.hasOwn(en, s)) return en[s];
  if (!/[\u3400-\u9fff]/.test(s)) return s;
  let m;
  if ((m = s.match(/^(\d+) (?:条报警待处理|项报警)$/))) return m[1] + (m[1] === '1' ? ' active alarm' : ' active alarms');
  if ((m = s.match(/^(\d+) 条待确认$/))) return m[1] + ' pending';
  if ((m = s.match(/^([\d /]+) 已载入$/))) return m[1] + ' loaded';
  if ((m = s.match(/^电机 (\d+)$/))) return 'Motor ' + m[1];
  if ((m = s.match(/^切换为(.+)模式$/))) return 'Switch to ' + english(m[1]) + ' mode?';
  if ((m = s.match(/^旧版耗材安装图(\d+)$/))) return 'Installation photo ' + m[1];
  if ((m = s.match(/^电机 (.+) 测试按键预览$/))) return 'Motor test preview: ' + english(m[1]);
  if ((m = s.match(/^(.+)测试按键预览$/))) return english(m[1]) + ' test preview';
  if ((m = s.match(/^音量 (\d+%)$/))) return 'Volume ' + m[1];
  // An identifier or a device-provided source may contain Chinese; preserve it verbatim.
  if (s.startsWith('患者病历号：')) return 'Record ID: ' + s.slice(6);
  if (s.startsWith('报警来源 · ')) return 'Alarm source · ' + (s.slice(7)==='设备状态'?'Device status':s.slice(7));
  for (const [sep, join] of [[' · ', ' · '], ['：', ': '], ['，', ', ']]) {
    if (s.includes(sep)) return s.split(sep).map(english).join(join);
  }
  return s;
}
function localize(root) {
  if (!root || document.documentElement.lang !== 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const n = walker.currentNode;
    if (n.parentElement.closest('[data-verbatim]')) continue;
    if (/[\u3400-\u9fff]/.test(n.data)) n.data = n.data.replace(/\S[\s\S]*\S|\S/, english);
  }
  for (const el of [root, ...root.querySelectorAll('[aria-label],[alt]')]) {
    for (const attr of ['aria-label','alt']) if (el.hasAttribute(attr)) el.setAttribute(attr, english(el.getAttribute(attr)));
  }
}
